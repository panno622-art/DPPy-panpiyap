#!/usr/bin/env python3

fnumber = int(input("Give me the first number: "))
snumber = int(input("Give me the second number: "))

print("Thank you!")

print(f"{fnumber} + {snumber} = {fnumber + snumber}")
print(f"{fnumber} - {snumber} = {fnumber - snumber}")
print(f"{fnumber} / {snumber} = {fnumber / snumber}")
print(f"{fnumber} * {snumber} = {fnumber * snumber}")
